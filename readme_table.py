"""Regenerate the results tables in README.md (between the RESULTS markers) from results/*.json."""
import json, glob, re, statistics as st, collections

LABEL = {"tina_rp": "Tina `.Reuse_Port`", "tina": "Tina `.Coordinator`", "axum": "Rust Axum 0.8",
         "gofast": "Go fasthttp 1.75", "go": "Go net/http"}
runs = collections.defaultdict(list)
for f in sorted(glob.glob("results/*_r*.json")):
    name, n, r = re.match(r"results/([a-z_]+)_n(\d+)_c200_r(\d+)\.json", f).groups()
    d = json.load(open(f)); lp = d["latencyPercentiles"]
    runs[(name, int(n))].append(dict(rps=d["summary"]["requestsPerSec"], p50=lp["p50"]*1e3, p99=lp["p99"]*1e3,
                                     p999=lp["p99.9"]*1e3, ok=d["statusCodeDistribution"].get("200", 0),
                                     total=sum(d["statusCodeDistribution"].values())))
rows = {}
for (name, n), v in runs.items():
    rss = int(open(f"results/{name}_n{n}_c200_rss_kb").read()) / 1024
    rows[(name, n)] = dict(rps=st.median(x["rps"] for x in v), runs=[x["rps"] for x in v],
                           p50=st.median(x["p50"] for x in v), p99=st.median(x["p99"] for x in v),
                           p999=st.median(x["p999"] for x in v), rss=rss,
                           ok=sum(x["ok"] for x in v), total=sum(x["total"] for x in v))

out = ["| Cores | Server | Req/s (median) | Runs (k req/s) | vs Go net/http | p50 ms | p99 ms | p99.9 ms | RSS MB |",
       "|---:|---|---:|---|---:|---:|---:|---:|---:|"]
for n in (1, 4, 8):
    grp = sorted([(k, r) for (k, nn), r in rows.items() if nn == n], key=lambda kr: -kr[1]["rps"])
    base = rows[("go", n)]["rps"]
    for i, (k, r) in enumerate(grp):
        b = "**" if i == 0 else ""
        out.append(f"| {n if i == 0 else ''} | {b}{LABEL[k]}{b} | {b}{r['rps']:,.0f}{b} | "
                   f"{' / '.join(f'{x/1e3:.0f}' for x in r['runs'])} | {r['rps']/base:.2f}x | {r['p50']:.3f} | {r['p99']:.3f} | "
                   f"{r['p999']:.3f} | {r['rss']:.0f} |")
table = "\n".join(out)
non200 = sum(r['total'] - r['ok'] for r in rows.values())
total_req = sum(r['total'] for r in rows.values())

# scaling table: req/s per core and speed-up vs 1 core
sc = ["| Server | 1 core | 4 cores | 8 cores | Speed-up 1→4 | Speed-up 1→8 | Req/s per core at 8 |", "|---|---:|---:|---:|---:|---:|---:|"]
for k in ("tina_rp", "tina", "gofast", "axum", "go"):
    g = lambda n: rows.get((k, n), {}).get("rps")
    base = g(1) or g(1) 
    if k == "tina_rp":  # Reuse_Port needs >1 shard; 1-core point is the single-shard Tina server
        base = rows[("tina", 1)]["rps"]
    cell = lambda n: f"{g(n):,.0f}" if g(n) else "n/a"
    sc.append(f"| {LABEL[k]} | {cell(1) if g(1) else f'{base:,.0f}*' } | {cell(4)} | {cell(8)} | {g(4)/base:.2f}x | {g(8)/base:.2f}x | {g(8)/8:,.0f} |")
scaling = "\n".join(sc)

block = f"""<!-- RESULTS:START (generated by readme_table.py) -->
### Full results

Median of 3 × 10 s runs per cell; `oha` with 200 keep-alive connections; "vs Go net/http" is the ratio at the same core count.
Best server per core count in **bold**. Across all runs, {total_req:,} responses were received and {non200} were not `200`.
(oha also reports ~199 requests per run as "aborted due to deadline": in-flight requests cut off when the timer ends, identical for every server.)

{table}

### Scaling

{scaling}

\\* Tina `.Reuse_Port` needs more than one shard, so it has no 1-core run; the speed-up is relative to the single-shard Tina server
(identical code path at 1 shard).
<!-- RESULTS:END -->"""
s = open("README.md").read()
if "<!-- RESULTS:START" in s:
    s = re.sub(r"<!-- RESULTS:START.*?<!-- RESULTS:END -->", lambda m: block, s, flags=re.S)
else:
    s = s.replace("![results](results/benchmark.png)\n", "![results](results/benchmark.png)\n\n" + block + "\n", 1)
open("README.md", "w").write(s)
print(block)
